"""
fl_projection_value_constrained.py -- WHAT IS THE MODEL WORTH IN WINS WHEN YOU CANNOT FREELY CHOOSE ANY PLAYER?  (user 2026-10-28)
Same backtest as fl_projection_value_refresh.py (2025 -> 2026, 139 hitters, 113 pitchers, realised WAR ~ wins).  Two constraints:
  A  SMALLER CANDIDATE POOLS: choose K = 9 hitters / 5 pitchers from only M candidates (M from just above K up to 80 / 60); at M = K there is no choice and every method is worth the same.
  B  THE KNOWN STARS ARE NOT AVAILABLE: the top 10% / 20% / 30% by LAST YEAR'S stats are removed from the pool (priced out or taken), then K picks from random pools of 40 / 30 of the rest -- a team shopping where last year's numbers are already priced in.
Wins = realised WAR of the picks by each method minus the same for the other method (and vs random picks = K x the pool mean); random pools of size M, 3,000 draws, players bootstrapped (B = 200) for 90% intervals.
Output: output/projection_value_constrained_log.txt, output/projection_value_constrained.json
"""
import json
import warnings

import numpy as np
import pandas as pd

import fl_hitter_war_calibration as hwc  # noqa: F401  (frame already regenerated by fl_projection_value_refresh.py; the parquet is read by pv.hitters)
import fl_pitcher_features as fp
import fl_projection_value_test as pv

warnings.filterwarnings("ignore")


def stats(D, K, M, rng, reps, drop_top=0.0):
    """mean over random pools of size M of [MODEL - last year, MODEL - random, last year - random] (wins); drop_top removes that share of the pool with the best LAST-YEAR projection first."""
    if drop_top > 0:
        D = D[D["NAIVE-1"].rank(pct=True, ascending=False) > drop_top].reset_index(drop=True)
    n = len(D); real = D["real"].to_numpy(); mo, n1 = D["MODEL"].to_numpy(), D["NAIVE-1"].to_numpy(); M = min(M, n); out = np.zeros((reps, 3))
    for r in range(reps):
        i = rng.choice(n, M, replace=False); sel = lambda p: i[np.argsort(-p[i])[:K]]; a, b = real[sel(mo)].sum(), real[sel(n1)].sum(); rnd = K * real[i].mean(); out[r] = [a - b, a - rnd, b - rnd]
    return out.mean(axis=0)


def run(D, label, K, Ms, drops, res, M_drop):
    rng = np.random.default_rng(5); rows = []
    for M in Ms:
        est = stats(D, K, M, rng, 3000); bs = np.array([stats(D.iloc[rng.integers(0, len(D), len(D))].reset_index(drop=True), K, M, rng, 200) for _ in range(200)])
        ci = lambda j: f"[{np.percentile(bs[:, j], 5):+.2f}, {np.percentile(bs[:, j], 95):+.2f}]"
        rows.append({"candidates M": M, "MODEL - last year": est[0], "90%": ci(0), "MODEL - random": est[1], "90% ": ci(1), "last year - random": est[2]})
    A = pd.DataFrame(rows); print(f"\n{label}: A. SMALLER CANDIDATE POOLS (K = {K} picks; wins per season)\n" + A.round(2).to_string(index=False)); res[label + " A"] = A.to_dict("records"); rows = []
    for d in drops:
        est = stats(D, K, M_drop, rng, 3000, d); bs = np.array([stats(D.iloc[rng.integers(0, len(D), len(D))].reset_index(drop=True), K, M_drop, rng, 200, d) for _ in range(200)])
        ci = lambda j: f"[{np.percentile(bs[:, j], 5):+.2f}, {np.percentile(bs[:, j], 95):+.2f}]"
        rows.append({"top by last year removed": f"{int(d * 100)}%", "MODEL - last year": est[0], "90%": ci(0), "P(> 0)": float(np.mean(bs[:, 0] > 0)), "MODEL - random": est[1], "90% ": ci(1), "last year - random": est[2]})
    B = pd.DataFrame(rows); print(f"\n{label}: B. KNOWN STARS UNAVAILABLE (K = {K} picks from random pools of {M_drop}; wins per season)\n" + B.round(2).to_string(index=False)); res[label + " B"] = B.to_dict("records")


def main():
    fp.WH_SVA_ESTIMATOR = "swstr_ct"; H = pv.hitters(); P = pv.pitchers()
    H = H.replace([np.inf, -np.inf], np.nan).dropna().reset_index(drop=True); P = P.replace([np.inf, -np.inf], np.nan).dropna().reset_index(drop=True); print(f"hitters pool {len(H)}, pitchers pool {len(P)}"); res = {}
    run(H, "HITTERS", 9, (10, 12, 14, 18, 25, 40, 80), (0.0, 0.1, 0.2, 0.3), res, 40); run(P, "PITCHERS", 5, (6, 7, 8, 10, 15, 25, 40, 60), (0.0, 0.1, 0.2, 0.3), res, 30)
    json.dump(res, open("output/projection_value_constrained.json", "w"), indent=1, default=float)


if __name__ == "__main__":
    main()
